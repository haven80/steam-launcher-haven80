# Builds both projects from the shared sources:
#   out/steam-launcher.wh.cpp   the Windhawk mod (one file, page embedded)
#   out/SteamLauncher.cpp       the standalone program's single source
#   out/SteamLauncher.exe       when a MinGW-w64 cross compiler is available
import base64, pathlib, re, shutil, subprocess, sys

root = pathlib.Path(__file__).parent
out = root / "out"; out.mkdir(exist_ok=True)

html = (root / "steam-launcher.html").read_text(encoding="utf-8")
tpl = (root / "mod" / "steam-launcher.template.cpp").read_text(encoding="utf-8")
if ")__wh_html__" in html:
    sys.exit("the page contains the raw string delimiter")

# The artifact host wraps the page in a document; the launcher serves it as a
# file, so it needs its own document head (above all the charset).
head = ('<!doctype html>\n<html>\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n')
page = head + html.replace('<canvas id="gl"', '</head>\n<body>\n<canvas id="gl"', 1) + "\n</body>\n</html>\n"
mod = tpl.replace("@@HTML@@", page, 1)
(out / "steam-launcher.wh.cpp").write_text(mod, encoding="utf-8", newline="\n")

# Standalone: the shim, the shared core, then the program's own host code.
a = mod.index("// @@CORE-BEGIN"); b = mod.index("// @@CORE-END")
core = mod[a:b]
shim = (root / "standalone" / "wh_shim.h").read_text(encoding="utf-8")
host = (root / "standalone" / "host.cpp").read_text(encoding="utf-8")
banner = ("// Steam Launcher, standalone program. Generated by build.py from the shared\n"
          "// sources; edit mod/steam-launcher.template.cpp, standalone/*, steam-launcher.html.\n\n")
std = banner + shim.replace("#pragma once\n", "") + "\n" + core + "\n" + host
(out / "SteamLauncher.cpp").write_text(std, encoding="utf-8", newline="\n")
# One version number, from host.cpp, for the resources and the manifest.
version = re.search(r'kVersion\[\] = L"([0-9.]+)"', host).group(1)
parts = (version.split(".") + ["0"] * 4)[:4]
shutil.copy(root / "standalone" / "app.ico", out / "app.ico")
for f in ("app.manifest", "resources.rc"):
    text = (root / "standalone" / f).read_text(encoding="utf-8")
    text = text.replace("@VERSION_COMMA@", ",".join(parts)).replace("@VERSION_DOTTED@", ".".join(parts))
    (out / f).write_text(text.replace("@VERSION@", version), encoding="utf-8")
print("sources ok", "v" + version, len(mod), len(std))

cxx = shutil.which("x86_64-w64-mingw32-g++"); rc = shutil.which("x86_64-w64-mingw32-windres")
if cxx and rc and "--no-exe" not in sys.argv:
    subprocess.run([rc, "resources.rc", "-O", "coff", "-o", "resources.o"], cwd=out, check=True)
    subprocess.run([cxx, "-std=c++20", "-O2", "-municode", "-mwindows", "-DUNICODE", "-D_UNICODE",
                    "-D_WIN32_WINNT=0x0A00", "-DWINVER=0x0A00", "-fno-devirtualize", "-Wall", "-Wno-unused-function",
                    "-Wno-cast-function-type", "-Wno-missing-field-initializers",
                    "SteamLauncher.cpp", "resources.o", "-o", "SteamLauncher.debug.exe", "-g1",
                    "-static", "-static-libgcc", "-static-libstdc++",
                    "-lole32", "-lshell32", "-lshlwapi", "-luuid", "-ladvapi32", "-luser32", "-lgdi32",
                    "-lwinhttp", "-ldwmapi"], cwd=out, check=True)
    # the shipped exe is the same binary without symbols, so crash offsets match
    strip = shutil.which("x86_64-w64-mingw32-strip")
    subprocess.run([strip, "-s", "SteamLauncher.debug.exe", "-o", "SteamLauncher.exe"], cwd=out, check=True)
    print("exe ok", (out / "SteamLauncher.exe").stat().st_size)
